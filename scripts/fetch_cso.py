#!/usr/bin/env python3
"""Fetch Irish GDP from the CSO API and regenerate data/gdp.js.

Usage: python3 scripts/fetch_cso.py
"""
import csv
import io
import json
import re
import urllib.request
from pathlib import Path

CSV_URL = "https://ws.cso.ie/public/api.restful/PxStat.Data.Cube_API.ReadDataset/NAQ04/CSV/1.0/en"
STATISTIC = "NAQ04S02"  # GNP at constant market prices, seasonally adjusted
SECTOR = "007"  # Gross Domestic Product at Market Prices
ROOT = Path(__file__).resolve().parent.parent


def fetch_series():
    with urllib.request.urlopen(CSV_URL, timeout=60) as resp:
        text = resp.read().decode("utf-8-sig")
    series = {}
    for row in csv.DictReader(io.StringIO(text)):
        if row["STATISTIC"] != STATISTIC or row["C03331V04018"] != SECTOR:
            continue
        m = re.match(r"(\d{4})Q(\d)", row["Quarter"])
        if not m or not row["VALUE"]:
            continue
        t = int(m.group(1)) * 4 + int(m.group(2)) - 1
        series[t] = float(row["VALUE"])
    data = []
    for t in sorted(series):
        yoy = None
        if t - 4 in series:
            yoy = round((series[t] / series[t - 4] - 1) * 100, 2)
        data.append(
            {
                "quarter": f"{t // 4}Q{t % 4 + 1}",
                "gdp": series[t],
                "yoy": yoy,
            }
        )
    return data


def main():
    data = fetch_series()
    if not data:
        raise SystemExit("No data fetched from CSO API")
    out = ROOT / "data" / "gdp.js"
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w") as f:
        f.write("// Generated by scripts/fetch_cso.py - CSO table NAQ04\n")
        f.write("// quarter: e.g. \"2025Q4\"; gdp: EUR millions (seasonally adjusted, constant prices); yoy: year-on-year growth %\n")
        f.write("const GDP_DATA = ")
        json.dump(data, f, separators=(",", ":"))
        f.write(";\n")
    (ROOT / "data" / "gdp.json").write_text(json.dumps(data, indent=1))
    print(f"Wrote {len(data)} quarters ({data[0]['quarter']} to {data[-1]['quarter']}) to {out}")


if __name__ == "__main__":
    main()

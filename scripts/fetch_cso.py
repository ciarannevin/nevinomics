#!/usr/bin/env python3
"""Fetch Irish output indicators from the CSO API and regenerate data files.

Usage: python3 scripts/fetch_cso.py
"""
import csv
import io
import json
import re
import urllib.request
from pathlib import Path

CSO = "https://ws.cso.ie/public/api.restful/PxStat.Data.Cube_API.ReadDataset"
NAQ04_CSV = f"{CSO}/NAQ04/CSV/1.0/en"
NAQ05_CSV = f"{CSO}/NAQ05/CSV/1.0/en"
ROOT = Path(__file__).resolve().parent.parent

# NAQ04: seasonally adjusted, constant prices (chain linked)
NAQ04_STAT = "NAQ04S02"
GDP_SECTOR = "007"   # Gross Domestic Product at Market Prices
GNP_SECTOR = "009"   # Gross National Product at Market Prices
# NAQ05: seasonally adjusted, constant prices
NAQ05_STAT = "NAQ05S02"
MDD_SECTOR = "0155"  # Modified Final Domestic Demand


def fetch_csv(url):
    with urllib.request.urlopen(url, timeout=90) as resp:
        return resp.read().decode("utf-8-sig")


def extract(text, statistic, sector):
    series = {}
    for row in csv.DictReader(io.StringIO(text)):
        if row["STATISTIC"] != statistic or row["C03331V04018"] != sector:
            continue
        m = re.match(r"(\d{4})Q(\d)", row["Quarter"])
        if not m or not row["VALUE"]:
            continue
        t = int(m.group(1)) * 4 + int(m.group(2)) - 1
        series[t] = float(row["VALUE"])
    return series


def build_records(series):
    records = []
    for t in sorted(series):
        yoy = qoq = None
        if t - 4 in series:
            yoy = round((series[t] / series[t - 4] - 1) * 100, 2)
        if t - 1 in series:
            qoq = round((series[t] / series[t - 1] - 1) * 100, 2)
        records.append(
            {
                "quarter": f"{t // 4}Q{t % 4 + 1}",
                "value": series[t],
                "yoy": yoy,
                "qoq": qoq,
            }
        )
    return records


def write_js(name, records, path):
    with path.open("w") as f:
        f.write(f"// Generated by scripts/fetch_cso.py - CSO PxStat\n")
        f.write(f"// quarter, value (EUR millions, constant prices, seasonally adjusted), yoy/qoq growth %\n")
        f.write(f"const {name} = ")
        json.dump(records, f, separators=(",", ":"))
        f.write(";\n")


def main():
    naq04 = fetch_csv(NAQ04_CSV)
    gdp = extract(naq04, NAQ04_STAT, GDP_SECTOR)
    gnp = extract(naq04, NAQ04_STAT, GNP_SECTOR)
    naq05 = fetch_csv(NAQ05_CSV)
    mdd = extract(naq05, NAQ05_STAT, MDD_SECTOR)

    for label, s in [("GDP", gdp), ("GNP", gnp), ("MDD", mdd)]:
        if not s:
            raise SystemExit(f"No {label} data fetched from CSO API")

    out = ROOT / "data"
    out.mkdir(parents=True, exist_ok=True)

    gdp_rec, gnp_rec, mdd_rec = build_records(gdp), build_records(gnp), build_records(mdd)

    write_js("GDP_DATA", gdp_rec, out / "gdp.js")
    write_js("GNP_DATA", gnp_rec, out / "gnp.js")
    write_js("MDD_DATA", mdd_rec, out / "mdd.js")

    (out / "all.json").write_text(
        json.dumps({"gdp": gdp_rec, "gnp": gnp_rec, "mdd": mdd_rec}, indent=1)
    )

    print(f"GDP: {len(gdp_rec)} quarters ({gdp_rec[0]['quarter']} to {gdp_rec[-1]['quarter']})")
    print(f"GNP: {len(gnp_rec)} quarters ({gnp_rec[0]['quarter']} to {gnp_rec[-1]['quarter']})")
    print(f"MDD: {len(mdd_rec)} quarters ({mdd_rec[0]['quarter']} to {mdd_rec[-1]['quarter']})")
    latest = gdp_rec[-1]
    print(f"Latest GDP: {latest['quarter']} = {latest['value']:.0f}, yoy {latest['yoy']}, qoq {latest['qoq']}")


if __name__ == "__main__":
    main()

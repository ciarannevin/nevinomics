#!/usr/bin/env python3
"""Fetch Central Bank of Ireland Quarterly Bulletin forecasts and regenerate data/forecasts.js.

Scrapes the Forecast Summary table (Table 1) from the latest Quarterly Bulletin
page on centralbank.ie. The bulletin is updated quarterly (Q1-Q4); this script
discovers the latest available bulletin automatically.

Usage: python3 scripts/fetch_cbi_forecasts.py
"""
import json
import re
import html as h
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CBI = "https://www.centralbank.ie/publication/quarterly-bulletins/quarterly-bulletin-q{n}-{year}"
LIST_URL = "https://www.centralbank.ie/publication/quarterly-bulletins"

TRACKED_ROWS = {
    "Modified Domestic Demand": "MDD",
    "Modified Gross National Income (GNI*)": "GNI*",
    "Gross Domestic Product": "GDP",
    "Total Employment": "Employment",
    "Unemployment Rate": "Unemployment",
    "Harmonised Index of Consumer Prices (HICP)": "HICP",
    "HICP Excluding Food and Energy (Core HICP)": "Core HICP",
}


def fetch(url):
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0 (nevinomics data fetcher)"})
    with urllib.request.urlopen(req, timeout=120) as r:
        return r.read().decode("utf-8", errors="replace")


def parse_table(raw):
    """Return (years, {indicator_full_name: [values...]}) from the first revisions-free block."""
    tables = re.findall(r"<table.*?</table>", raw, re.S)
    for t in tables:
        if "Gross Domestic Product" not in t or "Modified Domestic Demand" not in t:
            continue
        rows = re.findall(r"<tr.*?</tr>", t, re.S)
        years = None
        data = {}
        for row in rows:
            cells = [
                h.unescape(re.sub(r"<[^>]+>", "", c)).strip()
                for c in re.findall(r"<t[dh][^>]*>(.*?)</t[dh]>", row, re.S)
            ]
            if not cells:
                continue
            if years is None and all(re.fullmatch(r"\d{4}f?", c) for c in cells[1:] if c):
                years = [c.rstrip("f") for c in cells if c]
                continue
            label = cells[0]
            if label in TRACKED_ROWS and label not in data:
                vals = []
                for c in cells[1:]:
                    m = re.fullmatch(r"(-?\d+(?:\.\d+)?)", c)
                    vals.append(float(m.group(1)) if m else None)
                data[label] = vals
        if years and data:
            return years, data
    return None, None


def latest_bulletin():
    """Find the newest bulletin URL from the bulletins index page."""
    raw = fetch(LIST_URL)
    links = re.findall(r'href="(/publication/quarterly-bulletins/quarterly-bulletin[^"]+)"', raw)
    best = None
    for link in links:
        m = re.search(r"quarterly-bulletin-(?:quarter-)?(q(\d))-(\d{4})", link)
        if not m:
            continue
        q, year = int(m.group(2)), int(m.group(3))
        if best is None or (year, q) > best[0]:
            best = ((year, q), "https://www.centralbank.ie" + link)
    return best[1] if best else None


def main():
    url = latest_bulletin()
    if not url:
        raise SystemExit("Could not find any Quarterly Bulletin link on the index page")
    print(f"Latest bulletin: {url}")
    raw = fetch(url)
    title_m = re.search(r"<title>(.*?)</title>", raw, re.S)
    title = h.unescape(title_m.group(1)).strip() if title_m else url
    print(f"Title: {title}")

    years, table = parse_table(raw)
    if not years or not table:
        raise SystemExit("Forecast table not found or parse failed on bulletin page")

    series = {}
    for label, short in TRACKED_ROWS.items():
        if label in table:
            series[short] = [
                {"year": y, "value": v} for y, v in zip(years, table[label])
            ]

    out = ROOT / "data" / "forecasts.js"
    with out.open("w") as f:
        f.write("// Generated by scripts/fetch_cbi_forecasts.py - Central Bank of Ireland Quarterly Bulletin\n")
        f.write("// year: forecast year; value: annual growth % (level for Unemployment Rate)\n")
        f.write("const FORECAST_DATA = ")
        json.dump(
            {
                "source": "Central Bank of Ireland Quarterly Bulletin",
                "url": url,
                "title": title,
                "series": series,
            },
            f,
            separators=(",", ":"),
        )
        f.write(";\n")
    (ROOT / "data" / "forecasts.json").write_text(
        json.dumps({"source": "Central Bank of Ireland Quarterly Bulletin", "url": url, "series": series}, indent=1)
    )
    print("Wrote", out)
    for short, pts in series.items():
        print(f"  {short}: " + ", ".join(f"{p['year']}={p['value']}" for p in pts))


if __name__ == "__main__":
    main()
